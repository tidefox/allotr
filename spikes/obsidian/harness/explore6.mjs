import { engines, newHarnessPage, startPlugin } from './lib.mjs';
const S='/tmp/claude-501/-home-tidefox-src-allotr/6386db03-f62d-48e6-aa4c-627b9ea1809e/scratchpad';
const browser = await engines[process.argv[2] ?? 'chromium'].launch();
const { page } = await newHarnessPage(browser, { viewport: { width: 390, height: 844 }, query: '?platform=ios' });
