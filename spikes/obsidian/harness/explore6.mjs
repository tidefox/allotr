await page.screenshot({path:`${S}/phone-cat.png`});
await step('pick', () => page.getByRole('menuitemradio').first().click());
await step('menugone', () => page.getByRole('menu').waitFor({ state: 'detached' }));
await step('save', () => dialog.getByRole('button', { name: /^Save$/ }).click());
await step('hidden', () => dialog.waitFor({ state: 'hidden' }));
